-- Trigger om automatisch student record aan te maken bij Auth signup
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.students (id, email, name, class)
  values (
    new.id, 
    new.email, 
    coalesce(new.raw_user_meta_data->>'name', 'Nieuwe Student'),
    coalesce(new.raw_user_meta_data->>'class', 'Klas Onbekend')
  )
  on conflict (id) do nothing;
  return new;
end;
$$ language plpgsql security definer;

