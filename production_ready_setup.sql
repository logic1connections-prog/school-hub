-- Quiz Validation Function
create or replace function validate_quiz_answers(
    p_student_id uuid,
    p_quiz_id bigint,
    p_answers jsonb
) returns jsonb language plpgsql security definer as $$
declare
    v_total_questions int;
    v_correct_count int := 0;
    v_score int;
    v_passed boolean;
    v_pass_threshold int;
    v_xp_worth int := 10; 
    v_category text;
    v_xp_column text;
begin
    select count(*), max(passing_score), max(category) 
    into v_total_questions, v_pass_threshold, v_category
    from quizzes where id = p_quiz_id;

    select count(*) into v_correct_count
    from (
        select (ans->>'question_id')::bigint as q_id, (ans->>'selected')::int as sel
        from jsonb_array_elements(p_answers) as ans
    ) a
    join questions q on q.id = a.q_id
    where q.correct_index = a.sel;

    v_score := v_correct_count * v_xp_worth;
    v_passed := v_correct_count >= v_pass_threshold;

    insert into student_progress (student_id, quiz_id, score, passed)
    values (p_student_id, p_quiz_id, v_score, v_passed)
    on conflict (student_id, quiz_id) 
    do update set 
        score = case when v_score > student_progress.score then v_score else student_progress.score end,
        passed = v_passed or student_progress.passed;

    v_xp_column := case v_category
        when 'Lassen' then 'xp_lassen'
        when 'Veiligheid' then 'xp_veiligheid'
        when 'Gereedschappen' then 'xp_gereedschappen'
        when 'Machines' then 'xp_machines'
        when 'Stappenplannen' then 'xp_stappenplannen'
        else 'xp_metaal'
    end;

    execute format('update students set %I = %I + %L where id = %L', 
                   v_xp_column, v_xp_column, v_score, p_student_id);

    return jsonb_build_object('score', v_score, 'passed', v_passed);
end;
$$;

-- Analytics Function
create or replace function get_quiz_stats()
returns jsonb language plpgsql security definer as $$
declare
    v_stats jsonb;
begin
    select jsonb_build_object(
        'total_attempts', (select count(*) from student_progress),
        'pass_rate', (
            case when (select count(*) from student_progress) > 0 
            then (select count(*) from student_progress where passed = true) * 100 / (select count(*) from student_progress)
            else 0 end
        ),
        'average_score', (select coalesce(round(avg(score)), 0) from student_progress),
        'difficult_questions', (
            select jsonb_agg(q) from (
                select question, 
                       round(count(case when selected = correct_index then 1 end) * 100.0 / count(*), 1) as success_rate
                from student_answers sa
                join questions q on q.id = sa.question_id
                group by question
                order by success_rate asc
                limit 5
            ) q
        ),
        'popular_categories', (
            select jsonb_agg(c) from (
                select category, count(*) as count
                from quizzes quiz
                join student_progress p on p.quiz_id = quiz.id
                group by category
                order by count desc
                limit 5
            ) c
        )
    ) into v_stats;
    return v_stats;
end;
$$;

